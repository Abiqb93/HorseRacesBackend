const COLUMN = { GBP: 0, USD: 1, AUD: 2, NZD: 3 };
const MONTHS = Object.keys(EUR_PER_MONTH).sort();
export const FX_FROM = MONTHS[0];
export const FX_TO = MONTHS.at(-1);

/** The rates for a month (YYYY-MM), or for a year (YYYY: its average), clamped to the table. */
export function ratesFor(when) {
  const key = String(when ?? "").slice(0, 7);
  if (/^\d{4}-\d{2}$/.test(key)) {
    const m = key < FX_FROM ? FX_FROM : key > FX_TO ? FX_TO : key;
    return EUR_PER_MONTH[m];
  }
  const year = String(when ?? "").slice(0, 4);
  const months = MONTHS.filter((m) => m.startsWith(year));
  if (!months.length) return EUR_PER_MONTH[year < FX_FROM.slice(0, 4) ? FX_FROM : FX_TO];
  const sum = [0, 0, 0, 0];
  for (const m of months) EUR_PER_MONTH[m].forEach((v, i) => (sum[i] += v));
  return sum.map((v) => v / months.length);
}

/** Units of a currency per euro, at a month or a year. */
function perEuro(currency, when) {
  if (currency === "EUR") return 1;
  if (currency === "GNS") return ratesFor(when)[COLUMN.GBP] / 1.05;
  const i = COLUMN[currency];
  if (i === undefined) return null;
  return ratesFor(when)[i];
}

/** An amount from one currency into another, at the rates of a month (YYYY-MM) or a year (YYYY). */
export function convert(amount, from, to, when) {
  const v = Number(amount);
  if (amount === null || amount === undefined || amount === "" || !Number.isFinite(v)) return null;
  if (from === to) return v;
  const a = perEuro(from, when);
  const b = perEuro(to, when);
  if (!a || !b) return null;
  return (v / a) * b;
}

export default { EUR_PER_MONTH, FX_FROM, FX_TO, ratesFor, convert };
